import { test, expect } from '@playwright/test';
import { mkdir } from 'node:fs/promises';

test('bulk publishing, queued research, and SEO metadata editing work on desktop and mobile', async ({ page, request }) => {
    const errors = [];
    page.on('pageerror', error => errors.push(error.message));
    await page.setViewportSize({ width: 1440, height: 1000 });
    await page.goto('/staff/login');
    await page.getByLabel('Email address', { exact: true }).fill('bulk@browser.example.test');
    await page.getByLabel('Password', { exact: true }).fill('BrowserOnlyPassword123!');
    await page.getByRole('button', { name: 'Sign in', exact: true }).click();
    await expect(page).toHaveURL(/\/staff$/);
    for (const number of [1, 2]) {
        await page.goto('/staff/articles/create');
        await page.getByLabel('Article title', { exact: true }).fill(`Bulk browser fixture ${number}`);
        await page.getByLabel('Page address', { exact: true }).fill(`bulk-browser-fixture-${number}`);
        await page.getByLabel('Short introduction', { exact: true }).fill('Disposable workflow test content.');
        await page.getByLabel('Article body', { exact: true }).fill('## Test section\n\nFixture text for browser interaction testing only.');
        await page.getByLabel('Hero image URL', { exact: true }).fill('https://example.test/fixture.jpg');
        await page.getByLabel('Sources and research notes', { exact: true }).fill('Disposable fixture; no factual reporting or image-rights claim.');
        await page.getByRole('button', { name: 'Create draft', exact: true }).click();
        await expect(page).toHaveURL(/\/edit$/);
    }
    await page.goto('/staff/articles?q=Bulk+browser+fixture');
    await expect(page.locator('#article-batch button[type=submit]')).toBeDisabled();
    await page.getByLabel('Select visible articles', { exact: true }).check();
    await expect(page.locator('[data-selection-count]')).toHaveText('2 selected on this page');
    await page.getByLabel('Bulk action', { exact: true }).selectOption('publish');
    await page.getByRole('button', { name: 'Apply', exact: true }).click();
    await expect(page.getByRole('heading', { name: 'Publish selected articles', exact: true })).toBeVisible();
    expect((await request.get('/articles/bulk-browser-fixture-1')).status()).toBe(404);
    await page.getByRole('checkbox').check();
    await page.getByRole('button', { name: 'Publish 2 articles', exact: true }).click();
    await expect(page.getByRole('status')).toContainText('Selected articles published');
    expect((await request.get('/articles/bulk-browser-fixture-1')).status()).toBe(200);
    await page.goto('/staff/growth/integrations');
    const provider = page.getByRole('heading', { name: 'Google Gemini', exact: true }).locator('..');
    await provider.getByLabel('New Google Gemini key', { exact: true }).fill('browser-fixture-key-not-a-real-key');
    await provider.getByRole('button', { name: 'Encrypt and save key', exact: true }).click();
    await page.goto('/staff/articles?q=Bulk+browser+fixture');
    await page.getByLabel('Select visible articles', { exact: true }).check();
    await page.getByLabel('Bulk action', { exact: true }).selectOption('gemini');
    await page.getByRole('button', { name: 'Apply', exact: true }).click();
    await expect(page.getByRole('heading', { name: 'Research & optimise with Gemini', exact: true })).toBeVisible();
    await page.getByRole('checkbox').check();
    await page.getByRole('button', { name: 'Queue research & optimisation', exact: true }).click();
    await expect(page).toHaveURL(/\/staff\/seo-batches\/\d+$/);
    await expect(page.locator('[data-batch-summary]')).toContainText('2 pending');
    await mkdir('artifacts/seo-workflow', { recursive: true });
    await page.screenshot({ path: 'artifacts/seo-workflow/02-batch-progress.png', fullPage: true });
    await page.getByRole('link', { name: 'Review SEO results', exact: true }).first().click();
    await expect(page.getByRole('heading', { name: 'SEO workspace', exact: true })).toBeVisible();
    await page.getByText('Edit search metadata', { exact: true }).click();
    await page.getByLabel('Search title', { exact: true }).fill('A private metadata replacement');
    await page.getByRole('button', { name: 'Save metadata draft', exact: true }).click();
    await expect(page.getByRole('status')).toContainText('Search metadata saved');
    expect(await (await request.get('/articles/bulk-browser-fixture-1')).text()).not.toContain('A private metadata replacement');
    await page.screenshot({ path: 'artifacts/seo-workflow/01-seo-desktop.png', fullPage: true });
    await page.setViewportSize({ width: 390, height: 844 });
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
    await page.screenshot({ path: 'artifacts/seo-workflow/03-seo-mobile.png', fullPage: true });
    expect(errors).toEqual([]);
});
